G.t = function (key, vars) {
  let s = (G.T[G.lang] && G.T[G.lang][key]) || G.T.ru[key] || key;
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
};

G.setLang = function (lang) {
  G.lang = lang;
  try { localStorage.setItem('cv_saber_lang', lang); } catch (e) {}
  if (G.sceneName) G.setScene(G.sceneName);
};
